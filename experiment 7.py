class KSEC:
    x=100
    y=500
    def add(self):
        print("addition:",self.x+self.y)
    def subtract(self):
        print("subtraction:",self.y-self.x)
    def division(self):
        print("divide:",self.y/self.x)
    def multiply(self):
        print("multiply:",self.x*self.y)
himani=KSEC()
himani.add()
himani.subtract()
himani.division()
himani.multiply()
